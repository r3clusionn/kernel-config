#!/bin/sh
# Batch 5 kernel trim (non-security items). Usage: trim.sh <configfile> [profiling]
# Security-related options (LSMs, AUDIT, TPM, KFENCE) are deliberately NOT
# touched here; they need an explicit decision from the owner.
set -e
K=/usr/src/linux; F=$1
sc() { "$K/scripts/config" --file "$F" "$@"; }
sc --set-str LOCALVERSION "-min"
# power / wakeups
sc -d NO_HZ_FULL -e NO_HZ_IDLE -d IDLE_INJECT -d PSI -d SCHEDSTATS -d TASKSTATS -d TASK_DELAY_ACCT
# RAM / unused subsystems
sc -d MEMCG -d PAGE_OWNER -d SLUB_DEBUG -d KALLSYMS_ALL -d BPF_SYSCALL -d BLK_DEV_INITRD -d CMA \
   -d KPROBES -d FUNCTION_TRACER -d ACPI_DEBUG \
   -d HYPERVISOR_GUEST -d KEXEC -d KEXEC_FILE -d CRASH_DUMP -d X86_X32_ABI -d NUMA -d HIBERNATION \
   --set-val NR_CPUS 32
# workqueue-rescuer owners
sc -d EDAC -d QUOTA -d BLK_DEV_INTEGRITY -d BLK_DEV_THROTTLING -d NVME_HOST_AUTH -d PM_DEVFREQ
# GPU / NPU
sc -d HSA_AMD -d DRM_AMDGPU_SI -d DRM_AMDGPU_CIK -d DRM_AMD_DC_SI -d DRM_AMD_ISP -d DRM_ACCEL
# audio: keep ACP70 legacy + HDA + CS35L41 I2C
sc -d SND_SOC_SOF_TOPLEVEL -d SND_SOC_INTEL_SST_TOPLEVEL -d SND_SOC_INTEL_MACH \
   -d SND_SOC_AMD_RENOIR -d SND_SOC_AMD_ACP3x -d SND_SOC_AMD_ACP5x -d SND_SOC_AMD_ACP6x -d SND_SOC_AMD_PS \
   -d SND_SOC_AMD_ACP63_TOPLEVEL -d SND_SOC_AMD_ACP7X -d SND_SOC_AMD_SOUNDWIRE_LINK_BASELINE -d SND_HDA_SCODEC_CS35L41_SPI
# hardware this laptop does not have
sc -d ETHERNET -d MD -d ATA -d FUSION -d SCSI_LOWLEVEL -d NFS_FS -d BTRFS_FS -m EXT4_FS -d CAN -d INFINIBAND \
   -d PCCARD -d STAGING -d ACCESSIBILITY -d ANDROID_BINDER_IPC -d CHROME_PLATFORMS -d SURFACE_PLATFORMS \
   -d X86_PLATFORM_DRIVERS_DELL -d X86_PLATFORM_DRIVERS_UNIWILL -d INTEL_IOMMU -d INTEL_TXT -d MFD_INTEL_LPSS \
   -d INTEL_SOC_PMIC -d MACINTOSH_DRIVERS -d MEDIA_ANALOG_TV_SUPPORT -d MEDIA_DIGITAL_TV_SUPPORT \
   -d MEDIA_RADIO_SUPPORT -d MEDIA_TEST_SUPPORT -d MEDIA_PLATFORM_SUPPORT -d MEDIA_PCI_SUPPORT -d RC_CORE \
   -d USB_SERIAL -d INPUT_JOYSTICK -d INPUT_TABLET -d INPUT_TOUCHSCREEN -d INPUT_PCSPKR -d SP5100_TCO \
   -d HID_SENSOR_ALS -d HID_SENSOR_PROX
for v in ADMTEK ATH ATMEL BROADCOM CISCO INTEL INTERSIL MARVELL MEDIATEK MICROCHIP PURELIFI RALINK RSI SILABS ST TI ZYDAS QUANTENNA; do
  sc -d WLAN_VENDOR_$v
done
if [ "$2" = profiling ]; then
  sc -e MEM_ALLOC_PROFILING -e MEM_ALLOC_PROFILING_ENABLED_BY_DEFAULT
fi
# leftover debug / self-test infrastructure (not hardening)
sc -d KGDB -d FTRACE -d KPROBES -d STACK_TRACER -d CRYPTO_SELFTESTS -d DYNAMIC_DEBUG \
   -d DEBUG_SECTION_MISMATCH -d DEBUG_MEMORY_INIT -d DEBUG_SHIRQ -d RV -d X86_DECODER_SELFTEST \
   -d DEBUG_BOOT_PARAMS -d RUNTIME_TESTING_MENU -d NET_SELFTESTS -d OVMF_DEBUG_LOG -d FW_LOADER_DEBUG -d MEMTEST
